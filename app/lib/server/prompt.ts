export interface PromptContext {
  key?: string;
  dim?: string;
  summary?: string;
  reading?: { meta: string; body: string };
}

/** 把命主信息、当前维度文本、命盘骨架拼成系统提示词 */
export function buildSystem(ctx: PromptContext): string {
  const parts = [SYSTEM_PROMPT];

  if (ctx.reading) {
    parts.push('', '【命主】', ctx.reading.meta, '', '【本地解读库】', ctx.reading.body.slice(0, 6000));
  }
  if (ctx.summary) {
    parts.push('', '【命盘结构】', ctx.summary.slice(0, 2500));
  }
  return parts.join('\n');
}
